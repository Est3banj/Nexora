import { expect, test } from "@playwright/test";
import { dbOne, wipeSalesAndCatalog } from "./helpers-db";

const evidence = "/var/folders/zq/6h6qz_616b371m8v3q93wklh0000gn/T/opencode";
for (const width of [1440, 375]) {
  test(`13.3 catalog modal atomic offline create/edit, audit and responsive states ${width}`, async ({ page, context }) => {
    wipeSalesAndCatalog();
    dbOne("DELETE FROM categories");
    await page.setViewportSize({ width, height: 1000 });
    const org = dbOne("SELECT id FROM organization WHERE slug='tienda-demo'");
    await page.request.post("/api/auth/sign-in/email", { data: { email: "owner@demo.test", password: "demo12345" } });
    await page.request.post("/api/auth/organization/set-active", { data: { organizationId: org } });
    const offlineFlag = "pos:e2e-catalog-offline";
    await context.addInitScript(flag => Object.defineProperty(navigator, "onLine", { configurable: true, get: () => localStorage.getItem(flag) !== "1" }), offlineFlag);
    await page.goto("/");
    await page.getByTestId("tab-catalog").click();
    await expect(page.getByTestId("empty-catalog-note")).toContainText("Catálogo vacío");
    await page.getByText("Administrar categorías", { exact: true }).click();
    await page.getByTestId("new-category-name").fill("Bebidas");
    await page.getByTestId("category-create").click();
    await expect(page.getByTestId("catalog-category-filter").locator("option")).toHaveCount(3);
    await page.getByText("Administrar categorías", { exact: true }).click();
    await context.route("**/api/sync/**", route => route.abort());
    await page.evaluate(flag => localStorage.setItem(flag, "1"), offlineFlag);
    await context.setOffline(true);
    await page.evaluate(() => window.dispatchEvent(new Event("offline")));
    await page.getByTestId("product-new").click();
    const modal = page.getByTestId("product-modal");
    await expect(page.getByTestId("product-name")).toBeFocused();
    await page.getByTestId("product-name").fill("Café de origen");
    await page.getByTestId("product-category").selectOption({ label: "Bebidas" });
    await page.getByTestId("variant-name").fill("250 g");
    await page.getByTestId("variant-code").fill("000250");
    await page.getByTestId("variant-price").fill("12000");
    await page.getByTestId("variant-cost").fill("6000.5");
    await page.getByTestId("variant-stock").fill("12");
    await page.getByTestId("product-create").click();
    await expect(modal.getByRole("alert")).toContainText("enteros");
    await expect(modal.getByTestId("variant-cost")).toHaveAttribute("aria-describedby", "product-error");
    await page.getByTestId("variant-cost").fill("6000");
    await page.screenshot({ path: `${evidence}/m6-${width}-product-create.png`, fullPage: true });
    await modal.getByTestId("product-create").dblclick();
    await expect(modal).not.toBeVisible();
    await expect(page.getByTestId("product-new")).toBeFocused();
    const tile = page.getByTestId("product-item");
    await expect(tile).toHaveCount(1);
    await tile.getByTestId("product-edit").click();
    await modal.getByTestId("product-name").fill("Café de origen editado");
    await modal.getByTestId("add-variant").click();
    const first = modal.getByTestId("variant-row").first();
    const second = modal.getByTestId("variant-row").nth(1);
    await second.getByTestId("variant-name").fill("500 g");
    await second.getByTestId("variant-code").fill("000250");
    await second.getByTestId("variant-price").fill("22000");
    await second.getByTestId("variant-stock").fill("8");
    await modal.getByTestId("product-create").click();
    await expect(modal.getByRole("alert")).toContainText("ya pertenece");
    await expect(modal.getByTestId("product-name")).toHaveValue("Café de origen editado");
    await second.getByTestId("variant-code").fill("000500");
    await first.getByTestId("variant-stock").fill("-2");
    await modal.getByTestId("product-create").click();
    await expect(modal.getByRole("alert")).toBeVisible();
    await first.getByTestId("adjust-reason").fill("rotura");
    await first.getByTestId("adjust-note").fill("Dos envases dañados en recepción");
    await modal.getByText("Foto, icono y estado", { exact: true }).click();
    await modal.getByTestId("product-icon").selectOption("coffee");
    const png = await page.evaluate(() => {
      const canvas = document.createElement("canvas"); canvas.width = 32; canvas.height = 32;
      const ctx = canvas.getContext("2d")!; ctx.fillStyle = "#4f46e5"; ctx.fillRect(0, 0, 32, 32);
      return canvas.toDataURL("image/png").split(",")[1];
    });
    await modal.getByTestId("product-photo").setInputFiles({ name: "broken.png", mimeType: "image/png", buffer: Buffer.from("invalid image") });
    await expect(modal.getByRole("alert")).toContainText("No se pudo procesar");
    await modal.getByTestId("product-photo").setInputFiles({ name: "photo.png", mimeType: "image/png", buffer: Buffer.from(png, "base64") });
    await expect(modal.getByTestId("photo-preview")).toBeVisible();
    await modal.getByTestId("product-create").click();
    await expect(modal).not.toBeVisible();
    await expect(tile).toContainText("500 g");
    await expect(tile).toContainText("10 un.");
    await expect(tile.getByTestId("product-photo-thumb")).toBeVisible();
    // Vite's dev app shell is not precached. Restore transport only for reload;
    // navigator remains offline and sync stays blocked across navigation.
    expect(dbOne("SELECT count(*) FROM products")).toBe("0");
    await context.setOffline(false);
    await page.reload();
    await page.getByTestId("tab-catalog").click();
    await expect(tile).toContainText("500 g");
    await expect(tile).toContainText("10 un.");
    expect(dbOne("SELECT count(*) FROM products")).toBe("0");
    await tile.getByTestId("toggle-active").click();
    await expect(tile.getByTestId("toggle-active")).toHaveText("Inactivo");
    await page.getByTestId("tab-sale").click();
    await expect(page.getByTestId("sale-item")).toHaveCount(0);
    await page.getByTestId("tab-catalog").click();
    await tile.getByTestId("toggle-active").click();
    await expect(tile.getByTestId("toggle-active")).toHaveText("Activo");
    await context.unroute("**/api/sync/**");
    await page.evaluate(flag => localStorage.removeItem(flag), offlineFlag);
    await page.evaluate(() => window.dispatchEvent(new Event("online")));
    await expect(page.getByTestId("pending-badge")).toContainText("sinc.");
    expect(dbOne("SELECT count(*) FROM products")).toBe("1");
    expect(dbOne("SELECT count(*) FROM product_variants")).toBe("2");
    expect(dbOne("SELECT delta || ':' || reason || ':' || note FROM stockdiary WHERE reason='rotura'")).toBe("-2:rotura:Dos envases dañados en recepción");
    const replay = await page.evaluate(async () => (window as unknown as { __pos: { repushSynced(): Promise<Array<{ status: string }>> } }).__pos.repushSynced());
    expect(replay.every(row => row.status === "duplicate")).toBe(true);
    expect(dbOne("SELECT count(*) FROM stockdiary WHERE reason='rotura'")).toBe("1");
    await page.reload();
    await page.getByTestId("tab-catalog").click();
    await expect(tile).toContainText("000250");
    await tile.getByTestId("product-edit").click();
    await expect(first.getByTestId("variant-cost")).toHaveValue("6000");
    await expect(modal.getByTestId("product-photo")).toBeAttached();
    await modal.getByTestId("product-name").fill("X".repeat(120));
    await page.screenshot({ path: `${evidence}/m6-${width}-product-edit.png`, fullPage: true });
    expect(await modal.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    if (width === 375) {
      await page.setViewportSize({ width, height: 600 });
      await modal.getByTestId("product-create").scrollIntoViewIfNeeded();
      await expect(modal.getByTestId("product-create")).toBeInViewport();
      const bounds = (await modal.boundingBox())!;
      expect(bounds.y).toBeGreaterThanOrEqual(16);
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(584);
      await page.screenshot({ path: `${evidence}/m6-375-product-short-viewport.png`, fullPage: true });
      await page.setViewportSize({ width, height: 1000 });
    }
    await page.keyboard.press("Escape");
    await expect(tile.getByTestId("product-edit")).toBeFocused();
    await expect(tile).not.toContainText("X".repeat(120));
    await page.getByTestId("catalog-search").fill("000500");
    await expect(tile).toHaveCount(1);
    await page.getByTestId("catalog-category-filter").selectOption("");
    await expect(tile).toHaveCount(0);
    await expect(page.getByTestId("empty-catalog-note")).toContainText("Sin resultados");
    await page.getByTestId("catalog-category-filter").selectOption("all");
    await page.getByTestId("catalog-search").fill("");
    // Real API fixtures complete a four-column desktop grid (not mock UI state).
    for (const name of ["Agua mineral", "Galletas de avena", "Leche entera"]) {
      expect((await page.request.post("/api/catalog/products", { data: { name, variant: { name: "Único", price: 4000, cost: 2000, stock: 20 } } })).status()).toBe(201);
    }
    // A fresh browser DB is not needed: rehydrate adds server fixtures without wiping local work.
    await page.evaluate(async () => {
      const { getLocalDb } = await import("/src/db/instance.ts");
      const { rehydrateFromServer } = await import("/src/sync/rehydrate.ts");
      const { activeOrgId, authClient } = await import("/src/auth.ts");
      const handle = (await getLocalDb())!;
      await rehydrateFromServer(handle.db, activeOrgId((await authClient.getSession()).data)!);
    });
    await page.getByTestId("tab-sale").click();
    await page.getByTestId("tab-catalog").click();
    await expect(tile).toHaveCount(4);
    await page.screenshot({ path: `${evidence}/m6-${width}-catalog.png`, fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);
    const longTile = tile.filter({ hasText: "Leche entera" });
    await longTile.getByTestId("product-edit").click();
    await modal.getByTestId("product-name").fill("Leche entera de finca en envase retornable ".repeat(3).slice(0, 120));
    await modal.getByTestId("variant-code").fill("9".repeat(120));
    await modal.getByTestId("product-create").click();
    await expect(modal).not.toBeVisible();
    await expect(longTile).toContainText("9".repeat(120));
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width);
    await longTile.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${evidence}/m6-${width}-catalog-long-data.png`, fullPage: true });
  });
}
